#!/usr/bin/env python3
"""Build public/rr/brand/css/recolor.css from FreeScout's own CSS bundle.

Every rule in FreeScout's bundle that uses one of its blues is repeated with the blue swapped for a
Round Robin variable (by role: fill, fill hover, link text, link hover, tint, focus). The module loads
this file after style.css, so the same selectors win without !important, and the variant (Midnight or
Frost) only has to set the variables. Bootstrap's "info" colours (alerts, btn-info) are left alone.

Usage: python3 build_recolor.py <freescout-bundle.css> <out.css>
Get the bundle from any page's <link rel="stylesheet" href=".../css/builds/<hash>.css"> (rebuild after a FreeScout upgrade).
"""
import re
import sys

FILL = {'#0078d7', '#5897fb', '#3875d7', '#337ab7'}
FILL_HOVER = {'#005a9e', '#0068bd', '#106ebe', '#104a7d', '#286090', '#204d74', '#2e6da4', '#3e97eb', '#122b40'}
LINK = {'#0078d7', '#3197d6', '#337ab7', '#3e97eb', '#0068bd', '#005a9e', '#106ebe', '#104a7d', '#237ab3', '#1b5d88', '#194c6e', '#3f8abf'}
LINK_HOVER = {'#23527c', '#286090'}
TINT = {'#deecf9', '#c9e2f9', '#d1ecff', '#e5f1fb', '#cce4f7', '#d5f0ff', '#bce7ff', '#b3d4ff'}
FOCUS = {'#66afe9', '#abd2f1', '#7abce4', '#83b8db', '#659ac8', '#3197d6'}
ALL = FILL | FILL_HOVER | LINK | LINK_HOVER | TINT | FOCUS
HEX = re.compile(r'#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b')


def norm(h):
    h = h.lower()
    return '#' + ''.join(c * 2 for c in h[1:]) if len(h) == 4 else h


def role(prop, h):
    if h in TINT:
        return 'var(--rr-tint)'
    if 'shadow' in prop or 'outline' in prop:
        return 'var(--rr-focus)'
    if prop == 'color':
        if h in LINK_HOVER:
            return 'var(--rr-link-hover)'
        if h in LINK or h in FILL or h in FILL_HOVER:
            return 'var(--rr-link)'
    if prop.startswith('border'):
        if h in FOCUS and h not in FILL:
            return 'var(--rr-focus)'
        return 'var(--rr-primary-hover)' if h in FILL_HOVER else 'var(--rr-primary)'
    if prop.startswith('background'):
        if h in FILL_HOVER:
            return 'var(--rr-primary-hover)'
        if h in FILL:
            return 'var(--rr-primary)'
        if h in FOCUS:
            return 'var(--rr-focus)'
    return None


def blocks(css):
    """Yield (media_prefix or None, selector, body) for plain rules, one level of @media deep."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n, media, depth = 0, len(css), None, 0
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        head = css[i:j].strip()
        if head.startswith('@media') or head.startswith('@supports'):
            media, i = head, j + 1
            continue
        if head.startswith('@'):  # @font-face, @keyframes...: skip the whole block
            d, k = 1, j + 1
            while d and k < n:
                d += {'{': 1, '}': -1}.get(css[k], 0)
                k += 1
            i = k
            continue
        k = css.find('}', j)
        yield media, head.lstrip('}').strip(), css[j + 1:k]
        i = k + 1
        # closing brace of a media block right after this rule
        rest = css[i:].lstrip()
        if media and rest.startswith('}'):
            i = css.find('}', i) + 1
            media = None


def main(src, out):
    css = open(src, encoding='utf-8', errors='replace').read()
    rules, seen = [], set()
    for media, sel, body in blocks(css):
        if not sel or 'keyframes' in sel:
            continue
        decls = []
        for d in body.split(';'):
            if ':' not in d:
                continue
            prop, val = (x.strip() for x in d.split(':', 1))
            prop_l = prop.lower()
            hits = [h for h in HEX.findall(val) if norm(h) in ALL]
            if not hits:
                continue
            new = val
            for h in hits:
                r = role(prop_l, norm(h))
                if r:
                    new = new.replace(h, r)
            if new != val:
                decls.append(f'{prop}:{new}')
        if decls:
            rule = f'{sel}{{{";".join(decls)}}}'
            if media:
                rule = f'{media}{{{rule}}}'
            if rule not in seen:
                seen.add(rule)
                rules.append(rule)
    header = ('/* Generated by app/RoundRobin/Brand/tools/build_recolor.py from the FreeScout CSS bundle. Do not edit by hand.\n'
              '   FreeScout blues -> Round Robin variables set in brand.css (--rr-primary, --rr-primary-hover, --rr-link, --rr-link-hover, --rr-tint, --rr-focus). */\n')
    open(out, 'w').write(header + '\n'.join(rules) + '\n')
    print(f'{len(rules)} rules -> {out}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
